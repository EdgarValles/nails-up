from playwright.sync_api import sync_playwright
import sys
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
    pg = b.new_page(viewport={"width": 390, "height": 800})
    errs = []
    pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("file:///home/claude/nails-up/dist/index.html#demo")
    pg.wait_for_selector(".empty")
    print("empty:", pg.inner_text(".empty").split("\n")[0])
    pg.click("text=Nueva cita >> nth=0")
    pg.select_option("#f-client", "__new")
    pg.fill("#f-nn", "Ana López"); pg.fill("#f-np", "55 1234 5678")
    pg.wait_for_selector("#f-svc option:nth-child(2)", state="attached")
    pg.select_option("#f-svc", index=1)
    pg.click("text=Guardar cita")
    pg.wait_for_selector(".swatch")
    print("swatch:", pg.inner_text(".swatch").replace("\n", " | "))
    # empalme
    pg.click("text=Nueva cita >> nth=0")
    pg.select_option("#f-client", index=1)
    pg.select_option("#f-svc", index=1)
    pg.click("text=Guardar cita")
    pg.wait_for_selector(".note")
    print("aviso:", pg.inner_text(".note").split("\n")[0])
    pg.screenshot(path="/tmp/agenda-empalme.png")
    pg.click("text=Guardar de todos modos")
    pg.wait_for_timeout(300)
    print("citas:", pg.locator(".swatch").count())
    pg.click(".swatch >> nth=0"); pg.click("text=Cancelar cita"); pg.click("text=Sí, cancelar cita")
    pg.wait_for_timeout(300)
    print("canceladas:", pg.locator(".swatch.cancelada").count())
    pg.click("text=Semana"); pg.wait_for_selector(".week")
    pg.screenshot(path="/tmp/agenda-semana.png")
    print("errors:", errs)
    b.close()
